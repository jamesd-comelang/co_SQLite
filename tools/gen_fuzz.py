#!/usr/bin/env python3
"""Seeded fuzz differential for the tokenizer port.

SQLite's tokenizer gets its real-world breadth from the whole
TCL suite and from fuzzers. The port's equivalent: generate
inputs from SQL-ish fragments (chosen so fragment *adjacency*
creates the edge cases), run the pure C sqlite3GetToken over
them (tools/difftest.c), and check the Come port token-for-token.

Deterministic: a fixed seed makes the corpus a regression suite,
not a lottery. Regenerate with tools/run_fuzz.sh.

  gen_fuzz.py header   -- write tools/fuzz_corpus.h
  gen_fuzz.py come     -- write src/tokenizer/t/06_fuzz_test.co
                          from tools/expected_fuzz.txt
"""
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from corpus import c_escape, come_escape  # noqa: E402

SEED = 20261023
N_CASES = 400

FRAGMENTS = [
    # keywords and near-keywords
    "SELECT", "select", "SeLeCt", "FROM", "WHERE", "WITH", "RECURSIVE",
    "CURRENT_TIMESTAMP", "NATURAL", "LEFT", "JOIN", "WITHIN", "selection",
    "fromage", "x", "X", "y", "Y", "z", "_", "_a",
    # identifiers, incl. multibyte
    "a", "abc", "a1", "t1", "_x", "$x", "café", "αβ", "é", "tøm", "😀x",
    # numbers, good and malformed
    "0", "1", "42", "1.5", ".5", "5.", "1e10", "1E+10", "1e", "1e+",
    "1.0e", "1.0F", "0x", "0x1F", "0xG", "1_000", "1__2", "123abc",
    "9e9e9", "0b1", "3.14.15",
    # operators and punctuation
    "+", "-", "*", "/", "%", "=", "==", "<", "<=", ">", ">=", "<>",
    "!=", "!", "&", "|", "||", "~", "(", ")", ",", ";", ".", "->",
    "->>", "<<", ">>", "^", "?", "[", "]",
    # strings, quoted ids, blobs
    "'a'", "'it''s'", "''", "'a", "'", '"col"', '"a""b"', '"unterm',
    "`bt`", "[br]", "[a b]", "x'AB'", "x'ABC'", "X'ab12'", "x''", "x'",
    # comments
    "--c", "--", "/* c */", "/*", "/* ", "/**/", "--\n",
    # bind parameters
    "?12", ":nm", "@nm", "#nm", "$nm", "$nm::s", "$nm(x)", ":", "@",
    "$", "::",
    # whitespace and specials
    " ", "  ", "\t", "\n", "\v", "\f", "\r", "\ufeff",
]

SEPS = ["", "", "", " ", " ", " ", " ", "\t", "\n", "  ", "\v"]


def cases():
    rng = random.Random(SEED)
    out = []
    for _ in range(N_CASES):
        k = rng.randint(1, 7)
        parts = [rng.choice(FRAGMENTS) for _ in range(k)]
        s = parts[0]
        for p in parts[1:]:
            s += rng.choice(SEPS) + p
        out.append(s)
    return out


def write_header():
    cs = cases()
    lines = ["/* generated by tools/gen_fuzz.py -- do not edit */",
             f"static const int N_CASES = {len(cs)};",
             "static const char *cases[] = {"]
    for s in cs:
        lines.append("  " + c_escape(s) + ",")
    lines.append("};")
    path = os.path.join(ROOT, "tools", "fuzz_corpus.h")
    open(path, "w").write("\n".join(lines) + "\n")
    print("wrote", path)


def write_come():
    cs = cases()
    exp = {}
    for line in open(os.path.join(ROOT, "tools", "expected_fuzz.txt")):
        line = line.strip()
        if not line.startswith("case "):
            continue
        head, _, rest = line.partition(":")
        idx = int(head.split()[1])
        exp[idx] = [tuple(int(x) for x in tok.split(","))
                    for tok in rest.split()]
    assert len(exp) == len(cs), (len(exp), len(cs))

    out = []
    out.append("module fuzz_test")
    out.append("import std")
    out.append("import string")
    out.append("import tokenizer")
    out.append("")
    out.append("// GENERATED by tools/gen_fuzz.py (seed %d) -- inputs" % SEED)
    out.append("// composed from SQL fragments; expected streams from")
    out.append("// SQLite's own sqlite3GetToken (tools/difftest.c).")
    out.append("// Regenerate with tools/run_fuzz.sh -- do not edit.")
    out.append("")
    out.append("int failures = 0")
    out.append("")
    out.append("int cur_idx = 0")
    out.append("")
    out.append("void open_case(tokenizer tz, int idx, string sql) {")
    out.append("    cur_idx = idx")
    out.append("    tz.open(sql)")
    out.append("}")
    out.append("")
    out.append("void tok(tokenizer tz, string spec) {")
    out.append("    if (!tz.next()) {")
    out.append('        std.out.printf("FAIL fuzz %d: missing token, want %s\\n", cur_idx, spec)')
    out.append("        failures = failures + 1")
    out.append("        return")
    out.append("    }")
    out.append("    string f[] = spec.split(\":\")")
    out.append("    if (tz.typ() != int(f[0].tol()) || tz.start() != int(f[1].tol()) || tz.len() != int(f[2].tol())) {")
    out.append('        std.out.printf("FAIL fuzz %d: got %s(%d) @%d +%d, want %s\\n", cur_idx, tokenizer.token_name(tz.typ()), tz.typ(), tz.start(), tz.len(), spec)')
    out.append("        failures = failures + 1")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("void end_case(tokenizer tz) {")
    out.append("    if (tz.next()) {")
    out.append('        std.out.printf("FAIL fuzz %d: extra token %s @%d +%d\\n", cur_idx, tokenizer.token_name(tz.typ()), tz.start(), tz.len())')
    out.append("        failures = failures + 1")
    out.append("    }")
    out.append("}")
    out.append("")
    # Chunked into run_N functions: one construct holds at most
    # 1024 elements (COIL-147), and 400 cases in one main() break it.
    per = 100
    nchunks = (len(cs) + per - 1) // per
    for c in range(nchunks):
        out.append(f"void run_{c}(tokenizer tz) {{")
        for idx in range(c * per, min((c + 1) * per, len(cs))):
            out.append(f"    open_case(tz, {idx}, {come_escape(cs[idx])})")
            for t, s, ln in exp[idx]:
                out.append(f'    tok(tz, "{t}:{s}:{ln}")')
            out.append("    end_case(tz)")
        out.append("}")
        out.append("")
    out.append("int main() {")
    out.append("    var tz = tokenizer.create()")
    for c in range(nchunks):
        out.append(f"    run_{c}(tz)")
    out.append("    tz.destroy()")
    total = sum(len(v) for v in exp.values())
    out.append('    if (failures == 0) { std.out.printf("PASS: 06-fuzz (%d cases, %d tokens)\\n", %d, %d) }' % (len(cs), total, len(cs), total))
    out.append("    return failures")
    out.append("}")
    path = os.path.join(ROOT, "src", "tokenizer", "t", "06_fuzz_test.co")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "header":
        write_header()
    elif len(sys.argv) == 2 and sys.argv[1] == "come":
        write_come()
    else:
        sys.exit("usage: gen_fuzz.py header|come")
