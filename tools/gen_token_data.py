#!/usr/bin/env python3
"""Generate the SQLite token data used by src/tokenizer.co.

Two modes:

  --extract REF_DIR   Read a SQLite source tree (with a lemon-generated
                      parse.h in REF_DIR/gen/), write tools/token_data.json.
  (default)           Read tools/token_data.json and splice the generated
                      blocks into src/tokenizer.co between the
                      BEGIN/END GENERATED markers, and (re)write
                      docs/TOKEN_MAP.md.

Provenance: token values come from parse.h as generated by SQLite's own
tool/lemon.c from src/parse.y; the keyword list comes from the aKWList
table in SQLite's tool/mkkeywordhash.c. See docs/PROVENANCE.md.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def extract(ref):
    parse_h = open(os.path.join(ref, "gen", "parse.h")).read()
    tokens = [(name, int(val)) for name, val in
              re.findall(r"#define (TK_[A-Z_]+)\s+(\d+)", parse_h)]
    tokens.sort(key=lambda kv: kv[1])
    values = dict(tokens)
    # Keywords come from the GENERATED keywordhash.h (mkkeywordhash
    # run with its default feature set), not from aKWList in
    # mkkeywordhash.c: aKWList also lists feature-gated keywords such
    # as WITHIN (ORDERSET) that a default build never recognizes.
    kwh = open(os.path.join(ref, "gen", "keywordhash.h")).read()

    def carr(name, ty):
        body = re.search(name + r"\[\d+\] = \{(.*?)\};", kwh, re.S).group(1)
        if ty == "char":
            return re.findall(r"'(.)'", body)
        if ty == "name":
            return re.findall(r"TK_[A-Z_]+", body)
        return [int(x) for x in re.findall(r"\d+", body)]

    text = "".join(carr("zKWText", "char"))
    lens = carr("aKWLen", "int")
    offs = carr("aKWOffset", "int")
    codes = carr("aKWCode", "name")
    kws = []
    for i in range(1, len(lens)):
        word = text[offs[i]:offs[i] + lens[i]]
        kws.append({"word": word, "code": codes[i - 1],
                    "value": values[codes[i - 1]]})
    kws.sort(key=lambda k: k["word"])
    data = {"tokens": [{"name": n, "value": v} for n, v in tokens],
            "keywords": kws}
    out = os.path.join(ROOT, "tools", "token_data.json")
    with open(out, "w") as f:
        json.dump(data, f, indent=1)
    print(f"wrote {out}: {len(tokens)} tokens, {len(kws)} keywords")


def splice(path, marker, block):
    src = open(path).read()
    pat = re.compile(r"(// BEGIN GENERATED: " + marker + r"\n).*?"
                     r"(// END GENERATED: " + marker + r")", re.S)
    if not pat.search(src):
        sys.exit(f"markers for {marker} not found in {path}")
    src = pat.sub(lambda m: m.group(1) + block + m.group(2), src, count=1)
    open(path, "w").write(src)


def generate():
    data = json.load(open(os.path.join(ROOT, "tools", "token_data.json")))
    toks, kws = data["tokens"], data["keywords"]
    consts = "".join(f"    {t['name']} = {t['value']},\n" for t in toks)
    splice(os.path.join(ROOT, "src", "tokenizer", "tokenizer.co"),
           "token-consts", consts)

    fills = "".join(f'    m["{k["word"].lower()}"] = {k["value"]}\n'
                    for k in kws)
    splice(os.path.join(ROOT, "src", "tokenizer", "keywords.co"),
           "keyword-map", fills)

    cases = "".join(f'        case {t["value"]}:\n'
                    f'            return "{t["name"]}"\n' for t in toks)
    splice(os.path.join(ROOT, "src", "tokenizer", "names.co"),
           "token-name", cases)

    lines = ["# Token map — SQLite → Come", "",
             "Generated by `tools/gen_token_data.py` from SQLite's",
             "`parse.h` (lemon, from `src/parse.y`) and `tool/mkkeywordhash.c`.",
             "Do not edit by hand. Values are SQLite's parser token codes;",
             "the Come constants in `src/tokenizer/tokenizer.co` carry the same values.",
             "", "## Token types", "",
             "| Code | Constant | Produced by `get_token` |", "|---:|---|:---:|"]
    produced = set("""SEMI LP RP COMMA PLUS MINUS STAR SLASH REM EQ LE LT GE GT NE
LSHIFT RSHIFT BITOR BITAND BITNOT CONCAT PTR DOT INTEGER FLOAT QNUMBER BLOB
STRING ID VARIABLE SPACE COMMENT ILLEGAL WINDOW OVER FILTER""".split())
    produced |= {k["code"][3:] for k in kws}
    for t in toks:
        mark = "yes" if t["name"][3:] in produced else "— (parser-internal)"
        lines.append(f"| {t['value']} | `{t['name']}` | {mark} |")
    lines += ["", "## Keywords ( sqlite3KeywordCode )", "",
              "Recognized case-insensitively; the tokenizer returns the",
              "keyword's own code. `TEMP`/`TEMPORARY`, the `*_KW` join and",
              "like families, and `CURRENT_DATE`/`CURRENT_TIME`/",
              "`CURRENT_TIMESTAMP` share codes exactly as in SQLite.", "",
              "| Keyword | Code | Constant |", "|---|---:|---|"]
    for k in kws:
        lines.append(f"| {k['word']} | {k['value']} | `{k['code']}` |")
    lines.append("")
    open(os.path.join(ROOT, "docs", "TOKEN_MAP.md"), "w").write("\n".join(lines))
    print(f"spliced {len(toks)} consts, {len(kws)} keywords, "
          f"{len(toks)} name cases; rewrote docs/TOKEN_MAP.md")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--extract":
        extract(sys.argv[2])
    else:
        generate()
