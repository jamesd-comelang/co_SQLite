#!/usr/bin/env python3
"""The differential corpus: one list of SQL inputs, three consumers.

  python3 tools/corpus.py header   -> writes tools/corpus.h (C)
  python3 tools/corpus.py come     -> writes src/tokenizer/t/04_differential_test.co
                                      (needs tools/expected.txt, the
                                      output of the C harness; run
                                      tools/run_diff.sh to do it all)

The corpus is the single source of truth for the differential test:
every input here is tokenized by SQLite's own sqlite3GetToken (via
tools/difftest.c) and by the Come port, and the streams must match
exactly -- type, byte start, byte length.
"""

CASES = [
    "",
    "   \t\n  ",
    "SELECT 1",
    "select",
    "SeLeCt x",
    "selection",
    "select1",
    "fromage",
    "a", "ab", "_x", "x", "y", "z9", "$abc",
    "a>=b", "a<>b", "a!=b", "a|b", "a||b", "a->b", "a->>b",
    "a==b", "a<<2", "a>>2", "~a", "a%b", "a&b", "(a,b);",
    "!x", "^", "\v", "a\vb", " \v ",
    "'abc'", "'it''s'", "''", "'a", "'", "'a\nb'",
    '"my col"', "`weird`", '"a""b"', "[a b]", "[a", "[]", '"unterm',
    "42", "4.25", ".5", "5.", "1e10", "1E+10", "1.5e-2",
    "0x1F", "0XaB", "0x", "0xG", "123abc", "1e",
    "1_000", "0xAB_CD", "1_2.3_4", "1__2",
    "x'AB'", "X'ab12'", "x'ABC'", "x'AG'", "x'", "x'AB",
    "?", "?123", "?0", ":name", "@x", "#1", "$var", "$", ":", "@",
    "$a::b", "$fn(x)", "$fn(x", "$fn(a b)",
    "-- note\nSELECT", "--x", "/* c */", "/* c", "/*/", "/**/",
    "a/b", "x /*", "SELECT/*x*/1", "--\n",
    "a.b", "a.5", "END;",
    "CURRENT_TIMESTAMP", "NATURAL", "LEFT", "GLOB", "ISNULL",
    "NOTNULL", "TEMPORARY", "WITHIN",
    "\ufeffSELECT",
    "café", "αβ", "'a\U0001F600b'",
    "SELECT a, 'x' FROM t WHERE b >= 10 AND c IN (1, 2.5, x'0A') -- tail\n",
    "INSERT INTO t VALUES (?1, :two, @three, $four)",
    "CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT DEFAULT 'x''y')",
    "1e+", "1e-", ".e3", "0x1.5", "5..6", "'a''b''c'",
    "$a(b)c", "?abc", ":a:b", "x''", "x'AB' 'cd'",
]

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def c_escape(s):
    out = []
    for ch in s:
        for byte in ch.encode("utf-8"):
            if byte == 0x22:
                out.append('\\"')
            elif byte == 0x5C:
                out.append("\\\\")
            elif 0x20 <= byte < 0x7F:
                out.append(chr(byte))
            else:
                out.append("\\%03o" % byte)  # octal: fixed width, safe next to hex chars
    return '"' + "".join(out) + '"'


def come_escape(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif o == 0x0B:
            out.append("\\v")
        elif o == 0x0C:
            out.append("\\f")
        elif o < 0x20 or o == 0xFEFF:
            out.append("\\u%04X" % o)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def write_header():
    lines = ["/* generated by tools/corpus.py -- do not edit */",
             f"static const int N_CASES = {len(CASES)};",
             "static const char *cases[] = {"]
    for s in CASES:
        lines.append("  " + c_escape(s) + ",")
    lines.append("};")
    path = os.path.join(ROOT, "tools", "corpus.h")
    open(path, "w").write("\n".join(lines) + "\n")
    print("wrote", path)


def come_expr(s):
    """A Come expression evaluating to s. Come string literals
    cannot contain an escaped quote, so strings containing '"'
    are built by concatenation with dq (sprintf("%c", '"'))."""
    if '"' not in s:
        return come_escape(s)
    parts = s.split('"')
    terms = []
    for i, part in enumerate(parts):
        if part:
            terms.append(come_escape(part))
        if i < len(parts) - 1:
            terms.append("dq")
    return " + ".join(terms)


def write_come():
    exp = {}
    for line in open(os.path.join(ROOT, "tools", "expected.txt")):
        line = line.strip()
        if not line.startswith("case "):
            continue
        head, _, rest = line.partition(":")
        idx = int(head.split()[1])
        triples = []
        for tok in rest.split():
            t, s, ln = tok.split(",")
            triples.append((int(t), int(s), int(ln)))
        exp[idx] = triples
    assert len(exp) == len(CASES), (len(exp), len(CASES))

    out = []
    out.append("module differential_test")
    out.append("import std")
    out.append("import string")
    out.append("import tokenizer")
    out.append("")
    out.append("// GENERATED by tools/corpus.py from the corpus in")
    out.append("// tools/corpus.py and the expected streams produced by")
    out.append("// SQLite's own sqlite3GetToken (tools/difftest.c).")
    out.append("// Regenerate with tools/run_diff.sh -- do not edit.")
    out.append("")
    out.append("int failures = 0")
    out.append("")
    out.append("int cur_idx = 0")
    out.append("")
    out.append("void open_case(tokenizer tz, int idx, string sql) {")
    out.append("    cur_idx = idx")
    out.append("    tz.open(sql)")
    out.append("}")
    out.append("")
    out.append("void tok(tokenizer tz, string spec) {")
    out.append("    if (!tz.next()) {")
    out.append('        std.out.printf("FAIL case %d: missing token, want %s\\n", cur_idx, spec)')
    out.append("        failures = failures + 1")
    out.append("        return")
    out.append("    }")
    out.append("    string f[] = spec.split(\":\")")
    out.append("    if (tz.typ() != int(f[0].tol()) || tz.start() != int(f[1].tol()) || tz.len() != int(f[2].tol())) {")
    out.append('        std.out.printf("FAIL case %d: got %s(%d) @%d +%d, want %s\\n", cur_idx, tokenizer.token_name(tz.typ()), tz.typ(), tz.start(), tz.len(), spec)')
    out.append("        failures = failures + 1")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("void end_case(tokenizer tz) {")
    out.append("    if (tz.next()) {")
    out.append('        std.out.printf("FAIL case %d: extra token %s @%d +%d\\n", cur_idx, tokenizer.token_name(tz.typ()), tz.start(), tz.len())')
    out.append("        failures = failures + 1")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("int main() {")
    out.append('    string dq = sprintf("%c", \'"\')')
    out.append("    var tz = tokenizer.create()")
    for idx, sql in enumerate(CASES):
        tr = exp[idx]
        out.append(f"    open_case(tz, {idx}, {come_expr(sql)})")
        for t, s, ln in tr:
            out.append(f'    tok(tz, "{t}:{s}:{ln}")')
        out.append("    end_case(tz)")
    out.append("    tz.destroy()")
    out.append('    if (failures == 0) { std.out.printf("PASS: 04-differential (%d cases)\\n", ' + str(len(CASES)) + ") }")
    out.append("    return failures")
    out.append("}")
    path = os.path.join(ROOT, "src", "tokenizer", "t", "04_differential_test.co")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    if sys.argv[1] == "header":
        write_header()
    elif sys.argv[1] == "come":
        write_come()
